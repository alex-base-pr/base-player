"""Draw the Base Player mark and write it where the build expects it.

Pure Python (no Pillow): the mark is simple geometry — a dark rounded tile, a
screen outline and a play triangle — rendered with 4x supersampling.

    apps/base_player/icon.png        140x140 app tile
    apps/base_player/brand_logo.js   128x128 RGBA for the native renderer
    airplay/branding/base-player-logo.png   512x512 source image
"""
import base64
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / 'apps/base_player'
TILE, INK, ACCENT = (11, 16, 23), (255, 255, 255), (47, 155, 255)


def rounded(x, y, x0, y0, x1, y1, r):
    """Is (x, y) inside the rounded rectangle?"""
    if not (x0 <= x <= x1 and y0 <= y <= y1):
        return False
    cx = min(max(x, x0 + r), x1 - r)
    cy = min(max(y, y0 + r), y1 - r)
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r


def colour(u, v):
    """Colour and alpha at (u, v) in the unit square."""
    if not rounded(u, v, 0.0, 0.0, 1.0, 1.0, 0.22):
        return TILE, 0
    # play triangle, pointing right
    if 0.40 <= u <= 0.66 and abs(v - 0.47) <= (0.66 - u) * 0.62:
        return ACCENT, 255
    # screen outline
    if rounded(u, v, 0.16, 0.24, 0.84, 0.70, 0.07) and not rounded(u, v, 0.20, 0.28, 0.80, 0.66, 0.04):
        return INK, 255
    # stand
    if 0.34 <= u <= 0.66 and 0.775 <= v <= 0.81:
        return INK, 255
    return TILE, 255


def render(size, samples=4):
    out = bytearray()
    n = samples * samples
    for py in range(size):
        for px in range(size):
            r = g = b = a = 0
            for sy in range(samples):
                for sx in range(samples):
                    (cr, cg, cb), ca = colour((px + (sx + 0.5) / samples) / size, (py + (sy + 0.5) / samples) / size)
                    r += cr * ca; g += cg * ca; b += cb * ca; a += ca
            out += bytes((r // a, g // a, b // a, a // n)) if a else b'\0\0\0\0'
    return bytes(out)


def png(size, rgba):
    def chunk(kind, data):
        body = kind + data
        return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body) & 0xffffffff)
    rows = b''.join(b'\0' + rgba[y * size * 4:(y + 1) * size * 4] for y in range(size))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(rows, 9)) + chunk(b'IEND', b''))


def main():
    (ROOT / 'airplay/branding').mkdir(parents=True, exist_ok=True)
    (ROOT / 'airplay/branding/base-player-logo.png').write_bytes(png(512, render(512, 2)))
    (APP / 'icon.png').write_bytes(png(140, render(140)))
    encoded = base64.b64encode(zlib.compress(render(128), 9)).decode()
    (APP / 'brand_logo.js').write_text(
        "'use strict';\n// Generated by airplay/tools/prepare_brand.py.\n"
        "const ID = 0x42500001;\nconst pixels = require('zlib').inflateSync(Buffer.from('" + encoded + "', 'base64'));\n"
        "module.exports = { ID, pixels, register(setImage) { setImage(ID, 128, 128, pixels); } };\n", encoding='utf8')


if __name__ == '__main__':
    main()
